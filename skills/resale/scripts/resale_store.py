class _Dumper(yaml.SafeDumper):
    pass


def _str_repr(dumper: yaml.SafeDumper, data: str):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


_Dumper.add_representer(str, _str_repr)


def _canonical_yaml(item: Item) -> str:
    """Schema field order, literal blocks for multi-line, quoted ISO dates."""
    payload = item.model_dump(mode="json")
    return yaml.dump(
        payload,
        Dumper=_Dumper,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=100,
    )


def _atomic_write(path: Path, item: Item) -> None:
    text = _canonical_yaml(item)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".item.", suffix=".tmp")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(text)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    except BaseException:
        # BaseException on purpose: a KeyboardInterrupt between write and
        # rename is exactly what this cleanup exists for.
        Path(tmp).unlink(missing_ok=True)
        raise


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _rev(path: Path) -> str:
    return _sha256(path)[:12]


def slugify(name: str) -> str:
    s = unicodedata.normalize("NFKD", name or "")
    s = s.encode("ascii", "ignore").decode("ascii").lower()
    s = re.sub(r"[^a-z0-9]+", "-", s).strip("-")[:40].strip("-")
    return s or "item"


