def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="resale_store.py",
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = p.add_subparsers(dest="cmd", required=True)

    n = sub.add_parser("new", help="create an item (allocates the next uid)")
    n.add_argument("--name-en")
    n.add_argument("--name-zh")
    n.add_argument("--category", required=True)
    n.add_argument("--condition")
    n.add_argument("--price-ask", type=float)
    n.add_argument("--acq-date")
    n.add_argument("--acq-date-basis", default=None)
    n.add_argument("--acq-price", type=float)
    n.add_argument("--acq-source")
    n.add_argument("--acq-confidence")
    n.add_argument("--acq-platform")
    n.add_argument("--acq-order")
    n.add_argument(
        "--photos",
        nargs="*",
        help="files or a temp folder; verified, then the sources are DELETED",
    )
    n.add_argument("--set", nargs="*", help="extra key=value pairs")
    n.set_defaults(fn=_cmd_new)

    g = sub.add_parser("get", help="one item as JSON (includes rev, photos, tax)")
    g.add_argument("uid")
    g.set_defaults(fn=_cmd_get)

    l = sub.add_parser("ls", help="the current wave (--all adds years/)")
    l.add_argument("--all", action="store_true")
    l.add_argument("--unsold", action="store_true")
    l.add_argument("--sold", action="store_true", help="implies --all")
    l.add_argument("--json", action="store_true")
    l.set_defaults(fn=_cmd_ls)

    s = sub.add_parser(
        "set", help="set fields: set R002 price_ask=30 acquisition.price=89.99"
    )
    s.add_argument("uid")
    s.add_argument("pairs", nargs="+")
    s.add_argument("--rev")
    s.set_defaults(fn=_cmd_set)

    so = sub.add_parser(
        "sold", help="record a sale; refuses unless tax-complete; archives it"
    )
    so.add_argument("uid")
    so.add_argument("--platform", required=True)
    so.add_argument(
        "--price", type=float, help="FB/local/rednote: defaults to price_ask"
    )
    so.add_argument("--date", required=True, help="YYYY-MM-DD, from the order")
    so.add_argument("--approx", action="store_true", help="the date is approximate")
    so.add_argument(
        "--received",
        type=float,
        help="what reached the seller (eBay payout); FB/local/rednote default to --price",
    )
    so.add_argument("--ship-charged", type=float, help="shipping the buyer paid (eBay)")
    so.add_argument("--order")
    so.add_argument("--lot")
    so.add_argument("--rev")
    so.set_defaults(fn=_cmd_sold)

    for name, helptext in [
        ("kept", "keeping it (archives it)"),
        ("dispose", "thrown away / recycled (archives it)"),
        ("void", "phantom or duplicate record (archives it; uid stays reserved)"),
    ]:
        d = sub.add_parser(name, help=helptext)
        d.add_argument("uid")
        d.add_argument("--reason")
        d.add_argument("--date")
        d.add_argument("--rev")
        d.set_defaults(
            fn=_cmd_disposition, disposition={"dispose": "disposed"}.get(name, name)
        )

    ar = sub.add_parser(
        "archive", help="move every closed record still in items/ to years/"
    )
    ar.set_defaults(fn=_cmd_archive)

    c = sub.add_parser(
        "check", help="validate every record; exit 1 with the list on failure"
    )
    c.set_defaults(fn=_cmd_check)

    t = sub.add_parser(
        "tax", help="write years/<year>/tax.csv; refuses if any sale is incomplete"
    )
    t.add_argument("--year", type=int, default=date.today().year)
    t.set_defaults(fn=_cmd_tax)

    co = sub.add_parser(
        "correct", help="fix a closed record recorded wrongly (e.g. sold -> donated)"
    )
    co.add_argument("uid")
    co.add_argument("--to", required=True, choices=["kept", "disposed", "void"])
    co.add_argument("--date", required=True)
    co.add_argument("--reason", required=True)
    co.add_argument("--rev")
    co.set_defaults(fn=_cmd_correct)

    o = sub.add_parser(
        "order",
        help="add/replace one eBay order as Seller Hub shows it (the 1099-K source)",
    )
    o.add_argument("order_id")
    o.add_argument("--date", required=True)
    o.add_argument("--price", type=float, required=True)
    o.add_argument("--ship-charged", type=float, required=True)
    o.add_argument("--fees", type=float, required=True)
    o.add_argument("--ship-cost", type=float, required=True)
    o.add_argument("--refund", type=float, default=0)
    o.add_argument(
        "--status",
        required=True,
        choices=["completed", "partially_refunded", "refunded", "canceled"],
    )
    o.add_argument("--title")
    o.add_argument("--item-id")
    o.set_defaults(fn=_cmd_order)
    return p


def main(argv: list[str] | None = None) -> None:
    args = build_parser().parse_args(argv)
    try:
        args.fn(args)
    except Conflict as e:
        _die(3, str(e))
    except Invalid as e:
        _die(1, *e.errors)
    except (NotFound, ResaleError) as e:
        _die(1, str(e))


if __name__ == "__main__":
    main()
