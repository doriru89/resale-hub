def _strict_date(v: Any) -> Any:
    """Reject '2026-6-1'. YAML may already have parsed it into a date object."""
    if isinstance(v, str):
        if not ISO_DATE_RE.match(v):
            raise ValueError("date must be YYYY-MM-DD")
    return v


