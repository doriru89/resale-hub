def item_dir(uid: str) -> Path:
    """The current-wave folder. NotFound for an archived (or unknown) uid."""
    if not UID_RE.match(uid):
        raise Invalid(f"BAD_UID: {uid!r} is not R<digits>")
    d = items_dir()
    hits = sorted(p for p in d.glob(f"{uid}-*") if p.is_dir()) if d.exists() else []
    if not hits:
        raise NotFound(f"{uid}: no folder items/{uid}-*/")
    if len(hits) > 1:
        raise Conflict(
            f"{uid}: {len(hits)} folders claim this uid: "
            + ", ".join(p.name for p in hits)
        )
    return hits[0]


def _archived_paths(uid: str) -> list[Path]:
    d = years_dir()
    if not d.exists():
        return []
    return sorted(p for p in d.glob(f"*/{uid}.yaml") if YEAR_RE.match(p.parent.name))


def _is_archived(path: Path) -> bool:
    return path.parent.parent == years_dir()


def record_path(uid: str) -> Path:
    """items/<uid>-*/item.yaml or years/<year>/<uid>.yaml — exactly one."""
    if not UID_RE.match(uid):
        raise Invalid(f"BAD_UID: {uid!r} is not R<digits>")
    d = items_dir()
    folders = sorted(p for p in d.glob(f"{uid}-*") if p.is_dir()) if d.exists() else []
    hits = [f / "item.yaml" for f in folders] + _archived_paths(uid)
    if not hits:
        raise NotFound(f"{uid}: not in items/ or years/")
    if len(hits) > 1:
        raise Conflict(
            f"{uid}: {len(hits)} records claim this uid: "
            + ", ".join(str(h.relative_to(base())) for h in hits)
        )
    return hits[0]


def _label(path: Path) -> str:
    return (
        f"years/{path.parent.name}/{path.name}"
        if _is_archived(path)
        else path.parent.name
    )


def _parse(path: Path) -> Item:
    try:
        raw = yaml.safe_load(path.read_text(encoding="utf-8"))
    except yaml.YAMLError as e:
        raise Invalid(f"{_label(path)}: not valid YAML: {e}") from e
    if not isinstance(raw, dict):
        raise Invalid(f"{_label(path)}: expected a mapping, got {type(raw).__name__}")
    try:
        return Item.model_validate(raw)
    except ValidationError as e:
        raise Invalid(*(f"{_label(path)}: {_fmt(err)}" for err in e.errors())) from e


def _fmt(err: dict) -> str:
    loc = ".".join(str(x) for x in err["loc"]) or "<root>"
    return f"{loc}: {err['msg']}"


def load(uid: str) -> tuple[Item, str]:
    p = record_path(uid)
    if not p.exists():
        raise Invalid(f"{p.parent.name}: folder has no item.yaml")
    item = _parse(p)
    if item.uid != uid:
        raise Invalid(f"{_label(p)}: record says uid {item.uid!r}")
    return item, _rev(p)


def _scan(archived: bool = True) -> list[tuple[Item, str, Path]]:
    """Every record with its path. Raises Invalid listing ALL bad files."""
    out: list[tuple[Item, str, Path]] = []
    errs: list[str] = []
    seen: dict[str, str] = {}

    def take(f: Path, uid: str, where: str) -> None:
        if uid in seen:
            errs.append(f"{uid}: two records claim this uid ({seen[uid]}, {where})")
            return
        seen[uid] = where
        try:
            item = _parse(f)
        except Invalid as e:
            errs.extend(e.errors)
            return
        if item.uid != uid:
            errs.append(f"{where}: record says uid {item.uid!r}")
            return
        out.append((item, _rev(f), f))

    d = items_dir()
    for sub in sorted(p for p in d.iterdir() if p.is_dir()) if d.exists() else []:
        if not DIR_RE.match(sub.name):
            errs.append(f"{sub.name}: folder name must match R<digits>-<ascii-slug>")
            continue
        uid = sub.name.split("-", 1)[0]
        f = sub / "item.yaml"
        if uid in seen:
            errs.append(
                f"{uid}: two records claim this uid ({seen[uid]}, items/{sub.name})"
            )
        elif not f.exists():
            seen[uid] = f"items/{sub.name}"
            errs.append(
                f"{sub.name}: folder has no item.yaml (raw photos belong in intake/)"
            )
        else:
            take(f, uid, f"items/{sub.name}")

    y = years_dir()
    if archived and y.exists():
        for ydir in sorted(
            p for p in y.iterdir() if p.is_dir() and YEAR_RE.match(p.name)
        ):
            for f in sorted(ydir.iterdir()):
                m = ARCHIVE_RE.match(f.name)
                if m:
                    take(f, m.group(1), f"years/{ydir.name}/{f.name}")
    if errs:
        raise Invalid(*errs)
    return sorted(out, key=lambda r: int(r[0].uid[1:]))


def load_all(archived: bool = True) -> list[tuple[Item, str]]:
    """Every record (archived=False: the current wave only). Never skips a bad file."""
    return [(i, r) for i, r, _ in _scan(archived)]


def photos(uid: str) -> list[Path]:
    """Sorted upload set. An unsupported file is an ERROR, never a skip —
    a silently dropped HEIC means a listing goes up with fewer photos.
    An archived item has none (they are deleted on close)."""
    try:
        d = item_dir(uid) / "photos"
    except NotFound:
        if _archived_paths(uid):
            return []
        raise
    found = sorted(p for p in d.iterdir() if p.is_file()) if d.exists() else []
    bad = [p.name for p in found if p.suffix.lower() not in PHOTO_EXT]
    if bad:
        raise Invalid(f"{uid}/photos: {', '.join(sorted(bad))} not jpg")
    return found


def videos(uid: str) -> list[Path]:
    """Sorted videos/ (git-ignored, one copy only). Empty when there is none."""
    try:
        d = item_dir(uid) / "videos"
    except NotFound:
        return []
    return sorted(p for p in d.iterdir() if p.is_file()) if d.exists() else []


def _listing_photo_errors(item: Item, have: list[Path]) -> list[str]:
    """A platform's photo pick must name files that are in photos/, and a
    planned platform that can't take them all must have a pick — so the
    choice is on the record before the drafter starts."""
    names = {p.name for p in have}
    errs: list[str] = []
    for plat, lst in item.platforms.items():
        gone = [n for n in lst.photos or [] if n not in names]
        if gone:
            errs.append(
                f"PHOTO_MISSING: {item.uid} platforms.{plat}.photos names "
                f"{', '.join(gone)} — not in photos/"
            )
        cap = PHOTO_LIMIT.get(plat)
        if lst.status == "planned" and lst.photos is None and cap and len(have) > cap:
            errs.append(
                f"PHOTO_PICK_REQUIRED: {item.uid} has {len(have)} photos, {plat} takes "
                f"{cap} — set platforms.{plat}.photos=[<up to {cap} names, upload order>]"
            )
    return errs


