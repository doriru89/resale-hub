"""The single write path for resale inventory — library + CLI.

Two places hold records:

    items/R117-sodastream-terra/     the CURRENT WAVE (things for sale now)
        item.yaml                    tracked in git; the only truth for this item
        photos/                      gitignored; the upload set (jpg only)

    years/2026/                      everything closed in 2026
        R117.yaml                    same record, moved here on sold/kept/dispose/void
        tax.csv                      generated by `tax --year 2026`

Closing an item (sold, kept, disposed, void) deletes its photos, moves
item.yaml to years/<year>/<uid>.yaml and removes the folder. The year is the
sale date's year for a sale, the disposition date's year otherwise. A sale
must be tax-complete to close — there is no later backfill window.

Nothing else may write a record. The dashboard imports this module, skills call
the CLI. A hand Edit is blocked by the plugin hook `hooks/guard_resale_items.py`.

CLI:
    uv run resale_store.py <cmd> ...      (data lives in $RESALE_BASE, default ~/resale)

Exit codes: 0 written/ok · 1 Invalid or NotFound · 2 tax refused · 3 Conflict.
"""

