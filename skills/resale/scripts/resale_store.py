@dataclass
class _Intake:
    photos: list[Path] = field(default_factory=list)
    videos: list[Path] = field(default_factory=list)
    left: list[Path] = field(default_factory=list)
    junk: list[Path] = field(default_factory=list)
    dirs: list[Path] = field(default_factory=list)


def _dest_name(src: Path) -> str:
    return src.name if src.suffix.lower() in PHOTO_EXT else src.stem + ".jpg"


def _plan_intake(sources: list[Path]) -> _Intake:
    """Freeze the file list once. Folders are read one level deep; photos go to
    photos/, videos to videos/; anything else (pdf, a subfolder) is left where it is."""
    plan = _Intake()
    for s in sources:
        s = Path(s).expanduser().resolve()
        if any(m in f"{s}/" for m in CLOUD_MARKERS):
            raise Invalid(
                f"CLOUD_SOURCE: {s} is a synced folder — deleting there "
                "deletes in the cloud. Copy the photos to a local temp folder."
            )
        if s.is_dir():
            plan.dirs.append(s)
            children = sorted(s.iterdir())
        elif s.is_file():
            children = [s]
        else:
            raise NotFound(f"{s}: no such file or folder")
        for c in children:
            if c.name in JUNK:
                plan.junk.append(c)
            elif c.is_file() and c.suffix.lower() in PHOTO_EXT | CONVERT_EXT:
                plan.photos.append(c)
            elif c.is_file() and c.suffix.lower() in VIDEO_EXT:
                plan.videos.append(c)
            else:
                plan.left.append(c)
    for sub, files in (("photos", plan.photos), ("videos", plan.videos)):
        seen: dict[str, Path] = {}
        for p in files:
            n = _dest_name(p) if sub == "photos" else p.name
            if n.lower() in seen:
                raise Invalid(
                    f"NAME_COLLISION: {seen[n.lower()].name} and {p.name} would both "
                    f"become {sub}/{n} — rename one and retry"
                )
            seen[n.lower()] = p
    return plan


def _open_image(path: Path):
    from PIL import Image
    import pillow_heif

    pillow_heif.register_heif_opener()
    return Image.open(path)


def _dims(path: Path) -> tuple[int, int]:
    try:
        with _open_image(path) as im:
            im.load()
            return im.size
    except Exception as e:  # noqa: BLE001 — any decode failure is a refusal
        raise Invalid(
            f"VERIFY_FAILED: cannot read dimensions of {path.name}: {e}"
        ) from e


def _import_one(src: Path, dest_dir: Path, uid: str) -> dict:
    """Copy or convert one photo and PROVE the result before anyone deletes
    the source: jpg -> sha256 equal; heic/png -> the jpg decodes and has the
    source's pixel dimensions."""
    dest = dest_dir / _dest_name(src)
    row = {"source": str(src), "photo": f"{uid}/photos/{dest.name}"}
    if src.suffix.lower() in PHOTO_EXT:
        shutil.copy2(src, dest)
        a, b = _sha256(src), _sha256(dest)
        if a != b:
            raise Invalid(
                f"VERIFY_FAILED: {src.name}: copy sha256 != source — nothing deleted"
            )
        return row | {"sha8": a[:8]}
    try:
        with _open_image(src) as im:
            exif = im.info.get("exif")
            im.convert("RGB").save(
                dest, "JPEG", quality=95, **({"exif": exif} if exif else {})
            )
    except Exception as e:  # noqa: BLE001 — any decode/encode failure is a refusal
        raise Invalid(f"CONVERT_FAILED: {src.name}: {str(e)[:200]}") from e
    sw, sh = _dims(src)
    dw, dh = _dims(dest)
    if (sw, sh) != (dw, dh):
        raise Invalid(
            f"VERIFY_FAILED: {src.name} is {sw}x{sh} but the jpg is {dw}x{dh}"
        )
    return row | {"dims": f"{dw}x{dh}"}


def _import_video(src: Path, dest_dir: Path, uid: str) -> dict:
    """Videos are copied as-is and sha256-proved, like a jpg."""
    dest = dest_dir / src.name
    shutil.copy2(src, dest)
    a, b = _sha256(src), _sha256(dest)
    if a != b:
        raise Invalid(
            f"VERIFY_FAILED: {src.name}: copy sha256 != source — nothing deleted"
        )
    return {"source": str(src), "video": f"{uid}/videos/{dest.name}", "sha8": a[:8]}


def _finish_intake(plan: _Intake, imported: list[dict], moved: list[dict]) -> dict:
    """Every photo and video passed — only now do sources go. Emptied folders go too."""
    errors: list[str] = []
    for p in plan.photos + plan.videos + plan.junk:
        try:
            p.unlink()
        except OSError as e:
            errors.append(f"{p}: {e}")
    removed: list[str] = []
    for d in plan.dirs:
        try:
            if not any(d.iterdir()):
                d.rmdir()
                removed.append(str(d))
        except OSError:
            pass
    return {
        "imported": imported,
        "videos": moved,
        "left": [str(p) for p in plan.left],
        "removed_dirs": removed,
        "delete_errors": errors,
    }


def create(
    fields: dict, *, photos_from: list[Path] | None = None
) -> tuple[Item, str, dict]:
    """Allocate a uid, make the folder, import photos, write item.yaml.

    All-or-nothing: any failure removes the new folder and leaves every source
    file untouched. Sources are deleted only after every photo verified.
    Returns (item, rev, manifest).
    """
    today = date.today().isoformat()
    payload = dict(fields)
    payload.setdefault("created", today)
    payload["updated"] = today
    if payload.get("disposition", "available") != "available":
        raise Invalid(
            "CREATE_AVAILABLE_ONLY: new items join the current wave; "
            "close them with sold/kept/dispose/void"
        )
    plan = _plan_intake(photos_from or [])

    with _flock():
        uid = next_uid()
        payload["uid"] = uid
        name = payload.get("name_en") or payload.get("name_zh") or uid
        folder = items_dir() / f"{uid}-{slugify(name)}"
        try:
            folder.mkdir()  # atomic on APFS; EEXIST means someone raced us
        except FileExistsError as e:
            raise Conflict(f"{folder.name} already exists") from e
        try:
            _reject_unknown(payload)
            item = _validate(payload)
            (folder / "photos").mkdir()
            imported = [_import_one(p, folder / "photos", uid) for p in plan.photos]
            if plan.videos:
                (folder / "videos").mkdir()
            moved = [_import_video(p, folder / "videos", uid) for p in plan.videos]
            errs = _listing_photo_errors(item, sorted((folder / "photos").iterdir()))
            if errs:
                raise Invalid(*errs)
            _atomic_write(folder / "item.yaml", item)
        except BaseException:
            shutil.rmtree(folder, ignore_errors=True)
            raise
    return item, _rev(folder / "item.yaml"), _finish_intake(plan, imported, moved)


def update(
    uid: str, patch: dict, *, expected_rev: str | None = None, correction: bool = False
) -> tuple[Item, str]:
    """Read-modify-write under the store lock, with an optimistic-lock check.
    Closing an item archives it (see _write_record)."""
    with _flock():
        path = record_path(uid)
        if not path.exists():
            raise Invalid(f"{path.parent.name}: folder has no item.yaml")
        before = _parse(path)
        rev = _rev(path)
        if expected_rev is not None and expected_rev != rev:
            raise Conflict(
                f"{uid}: record changed since you read it "
                f"(you have {expected_rev}, on disk {rev}) — reload and re-apply"
            )
        if "uid" in patch and patch["uid"] != uid:
            raise Invalid(f"UID_IMMUTABLE: cannot rename {uid} to {patch['uid']!r}")
        nested = _deep_merge({}, patch)
        _reject_unknown(nested)
        _check_status_writes(nested, before)
        payload = _deep_merge(before.model_dump(mode="json"), patch)
        payload["uid"] = uid
        payload["updated"] = date.today().isoformat()
        after = _validate(payload)
        old, new = before.disposition, after.disposition
        if correction:
            # `correct`: a closed record was recorded wrongly — closed to closed only.
            if old not in CLOSED or new not in CLOSED - {"sold"}:
                raise Invalid(
                    f"CORRECTION: only closed -> kept/disposed/void ({old} -> {new})"
                )
        elif old != new:
            if _is_archived(path):
                raise Invalid(
                    f"ARCHIVED: {uid} is closed ({old}) in {_label(path)}; its disposition "
                    "cannot change. To sell it again, create a new item."
                )
            if new not in TRANSITIONS[old]:
                raise Invalid(f"ILLEGAL_TRANSITION: {old} -> {new}")
        if new == "available" and not _is_archived(path):
            errs = _listing_photo_errors(after, photos(uid))
            if errs:
                raise Invalid(*errs)
        dest = _write_record(path, after)
    return after, _rev(dest)


