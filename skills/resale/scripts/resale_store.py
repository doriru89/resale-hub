def _money(x: float | None) -> str:
    return "" if x is None else f"{x:.2f}"


def _year_sales(year: int) -> list[tuple[Item, dict]]:
    return [
        (i, t)
        for i, _ in load_all()
        if i.sale
        and (t := tax_view(i))
        and (i.sale.date is None or i.sale.date.year == year)
    ]


def _reconcile(sales: list[tuple[Item, dict]], orders: list[Order]) -> list[str]:
    """Every eBay sale is an order, every order that shipped is a sale, and the
    two agree to the cent. What eBay reports must be what the store holds."""
    problems: list[str] = []
    by_id = {o.order_id: o for o in orders}
    linked: dict[str, list[Item]] = {}
    for i, _ in sales:
        if i.sale.platform == "ebay" and i.sale.order_id:
            linked.setdefault(i.sale.order_id, []).append(i)
    for oid, items in linked.items():
        uids = ", ".join(i.uid for i in items)
        o = by_id.get(oid)
        if o is None:
            problems.append(
                f"{uids}: eBay order {oid} not in ebay_orders.json — add it with "
                "`order` from Seller Hub"
            )
            continue
        if o.status == "canceled":
            problems.append(
                f"{uids}: order {oid} was canceled, so it is not this item's sale — "
                "record where it really sold"
            )
            continue
        f = lambda v: v or 0  # noqa: E731
        mine = {
            "price": sum(i.sale.price for i in items),
            "ship_charged": sum(f(i.sale.shipping_charged) for i in items),
        }
        theirs = {"price": o.price, "ship_charged": o.ship_charged}
        if all(i.sale.received is None for i in items):
            for k, field in (
                ("fees", "fees"),
                ("ship_cost", "shipping_cost"),
                ("refund", "refund"),
            ):
                mine[k] = sum(f(getattr(i.sale, field)) for i in items)
                theirs[k] = getattr(o, k)
        else:
            mine["received"] = sum(tax_view(i)["net"] for i in items)
            theirs["received"] = o.earnings
        diff = [
            f"{k} {mine[k]:.2f} vs eBay {theirs[k]:.2f}"
            for k in theirs
            if abs(mine[k] - theirs[k]) > 0.005
        ]
        if diff:
            problems.append(f"{uids}: order {oid} disagrees — {'; '.join(diff)}")
    for o in orders:
        if o.order_id not in linked and o.status in ("completed", "partially_refunded"):
            problems.append(
                f"order {o.order_id} ({o.title[:40]}) shipped but no item records it"
            )
    return problems


def tax_report(year: int) -> dict:
    sales = _year_sales(year)
    problems = [
        f"{i.uid}: missing {', '.join(t['missing'])}"
        for i, t in sales
        if not t["complete"]
    ]
    orders = [o for o in load_orders(year) if o.date.year == year]
    problems += _reconcile(sales, orders)
    by_platform: dict[str, float] = {}
    for i, t in sales:
        by_platform[i.sale.platform] = round(
            by_platform.get(i.sale.platform, 0) + t["gross"], 2
        )
    gains = [(i, t) for i, t in sales if t["gain"]]
    on_1099k = [o for o in orders if o.status != "canceled"]
    gain_gross = sum(t["gross"] for i, t in gains if t["on_1099k"])
    return {
        "ok": not problems,
        "year": year,
        "filing": settings()["filing"],
        "problems": problems,
        "sales": len(sales),
        "gross": round(sum(t["gross"] for _, t in sales), 2),
        "gain": round(sum(t["gain"] or 0 for _, t in sales), 2),
        "gross_by_platform": by_platform,
        "ebay_orders": {
            "counted": len(on_1099k),
            "canceled": len(orders) - len(on_1099k),
            "gross": round(sum(o.gross for o in on_1099k), 2),
        },
        # Federal: the 1099-K line at the top of Schedule 1 — every order on the
        # 1099-K except the gross of gain sales, which go on Form 8949 instead.
        # Compare with the 1099-K eBay mails before entering it.
        "schedule1_1099k_entry": round(sum(o.gross for o in on_1099k) - gain_gross, 2),
        # On the 1099-K with no item behind them (refunded, the thing sold elsewhere).
        "orders_without_item": [
            {
                "order_id": o.order_id,
                "title": o.title,
                "status": o.status,
                "gross": round(o.gross, 2),
            }
            for o in on_1099k
            if not any(i.sale.order_id == o.order_id for i, _ in sales)
        ],
        "form_8949": [
            {"uid": i.uid, "gain": t["gain"], "holding": t["holding"]} for i, t in gains
        ],
    }


def _cmd_tax(a) -> None:
    year = a.year
    r = tax_report(year)
    if not r["ok"]:
        print(
            f"REFUSED: {len(r['problems'])} problem(s) in {year}. "
            "A partial worksheet is never written. Fix these, then re-run:"
        )
        for p in r["problems"]:
            print(f"  {p}")
        sys.exit(2)
    sales = _year_sales(year)
    out = None
    if sales:
        out = years_dir() / str(year) / "tax.csv"
        out.parent.mkdir(parents=True, exist_ok=True)
        with out.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh, lineterminator="\n")
            w.writerow(TAX_COLUMNS)
            for i, t in sales:
                s, acq = i.sale, i.acquisition
                w.writerow(
                    [
                        i.uid,
                        i.name_en or i.name_zh or "",
                        s.platform,
                        s.order_id or "",
                        acq.date.isoformat() if acq.date else "",
                        acq.date_basis,
                        s.date.isoformat(),
                        t["holding"] or "",
                        _money(acq.price),
                        acq.source or "",
                        _money(s.price),
                        _money(s.shipping_charged),
                        _money(t["gross"]),
                        _money(s.received),
                        _money(s.fees),
                        _money(s.shipping_cost),
                        _money(s.refund),
                        _money(t["net"]),
                        _money(t["gain"]),
                        "yes" if t["on_1099k"] else "",
                        _money(t["offset"]),
                    ]
                )
    del r["problems"]
    r["csv"] = str(out.relative_to(base())) if out else None
    print(json.dumps(r, ensure_ascii=False, indent=2))


