def _die(code: int, *msgs: str) -> None:
    print(
        json.dumps({"ok": False, "errors": list(msgs)}, ensure_ascii=False),
        file=sys.stderr,
    )
    sys.exit(code)


def _is_text(key: str) -> bool:
    """Does this dotted key name a text field? Text is stored verbatim — YAML
    parsing would turn 'Condition: used' into a dict and '820' into an int."""
    model: type[BaseModel] = Item
    parts = key.split(".")
    i = 0
    while i < len(parts):
        f = model.model_fields.get(parts[i])
        if f is None:
            return False  # unknown: let _reject_unknown say so
        if parts[i] == "platforms":
            model, i = Listing, i + 2
            continue
        ann = f.annotation
        sub = next(
            (
                c
                for c in (ann, *getattr(ann, "__args__", ()))
                if isinstance(c, type) and issubclass(c, BaseModel)
            ),
            None,
        )
        if sub is None:
            return i == len(parts) - 1 and str in (ann, *getattr(ann, "__args__", ()))
        model, i = sub, i + 1
    return False


def _kv(pairs: list[str]) -> dict:
    out: dict[str, Any] = {}
    for p in pairs:
        if "=" not in p:
            _die(1, f"expected key=value, got {p!r}")
        k, v = p.split("=", 1)
        k = k.strip()
        if v == "":
            out[k] = None
        elif _is_text(k):
            out[k] = v
        else:
            try:
                out[k] = yaml.safe_load(v)
            except yaml.YAMLError as e:
                raise Invalid(f"{k}: cannot parse {v!r}: {e.problem}") from e
    return out


def _intake_path(p: str) -> Path:
    """`--photos intake/<date>/<thing>/` is documented as store-relative; resolve it
    against base() when it does not exist relative to the cwd."""
    q = Path(p)
    if not q.exists() and (base() / p).exists():
        return base() / p
    return q


