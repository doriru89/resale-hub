# ---- eBay orders: the 1099-K is built from these, not from items ----------
# An order is not a sale: it can be canceled (off the 1099-K) or refunded with
# the item sold elsewhere (still on it). Items say what really happened to the
# thing; this ledger says what money went through eBay.
OrderStatus = Literal["completed", "partially_refunded", "refunded", "canceled"]


class Order(Strict):
    order_id: str
    date: Day
    title: str = ""
    item_id: Optional[str] = None
    price: float = Field(ge=0)
    ship_charged: float = Field(ge=0)
    fees: float = Field(ge=0)
    ship_cost: float = Field(ge=0)
    refund: float = Field(ge=0)
    status: OrderStatus

    @property
    def gross(self) -> float:  # what eBay's 1099-K counts (no sales tax)
        return self.price + self.ship_charged

    @property
    def earnings(self) -> float:
        return self.price + self.ship_charged - self.fees - self.ship_cost - self.refund


def orders_path(year: int) -> Path:
    return years_dir() / str(year) / "ebay_orders.json"


def load_orders(year: int) -> list[Order]:
    path = orders_path(year)
    if not path.exists():
        return []
    rows = json.loads(path.read_text(encoding="utf-8"))
    out, errs, seen = [], [], set()
    for n, row in enumerate(rows):
        try:
            o = Order.model_validate(row)
        except ValidationError as e:
            errs += [f"{path.name}[{n}]: {_fmt(err)}" for err in e.errors()]
            continue
        if o.order_id in seen:
            errs.append(f"{path.name}: order {o.order_id} appears twice")
        seen.add(o.order_id)
        out.append(o)
    if errs:
        raise Invalid(*errs)
    return out


def save_order(order: Order) -> None:
    year = order.date.year
    rows = [o for o in load_orders(year) if o.order_id != order.order_id] + [order]
    rows.sort(key=lambda o: (o.date, o.order_id))
    path = orders_path(year)
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(".json.tmp")
    tmp.write_text(
        json.dumps(
            [o.model_dump(mode="json") for o in rows], ensure_ascii=False, indent=1
        )
        + "\n",
        encoding="utf-8",
    )
    tmp.replace(path)


# Personal-use sales only — a loss is not income, a gain is (IRS Schedule D
# instructions). Who files and which platforms send a 1099-K depend on the
# household and its state, so they live in <base>/config.yaml.
DEFAULT_SETTINGS = {"filing": None, "form_1099k": ["ebay"]}


def settings() -> dict:
    p = base() / "config.yaml"
    loaded = (yaml.safe_load(p.read_text(encoding="utf-8")) or {}) if p.exists() else {}
    return DEFAULT_SETTINGS | loaded


COST_GATE = 0.6  # received >= 60% of an MSRP/estimate cost: a discount he likely
# got could make it a gain, so the real price paid (+ sales tax, shipping) is required
GUESSED_COST = {"msrp", "estimate"}


def tax_view(item: Item) -> dict | None:
    s = item.sale
    if s is None:
        return None
    gross = s.price + (s.shipping_charged or 0)
    cost = item.acquisition.price
    missing: list[str] = []
    if s.received is not None:
        net = s.received
    else:
        net = gross - (s.fees or 0) - (s.shipping_cost or 0) - (s.refund or 0)
        legacy = ("fees", "shipping_charged", "shipping_cost", "refund")
        if any(getattr(s, f) is None for f in legacy):
            missing.append("sale.received")
    if s.date is None:
        missing.append("sale.date")
    if cost is None:
        missing.append("acquisition.price")
    elif (
        item.acquisition.source in GUESSED_COST and net > 0 and net >= COST_GATE * cost
    ):
        missing.append("acquisition.real_cost")
    if s.platform == "ebay" and not s.order_id:
        missing.append("sale.order_id")
    holding = None
    if s.date and item.acquisition.date:
        holding = "long" if (s.date - item.acquisition.date).days > 365 else "short"
    # A gain (net above cost) goes on Form 8949 whatever the platform. A loss
    # is not deductible; if a 1099-K reported it, its whole gross is backed out
    # at the top of Schedule 1 — the gross, not the net, or fees and labels stay
    # taxed. No 1099-K, no loss to report (IRS 1099-K FAQ, Schedule D instr.).
    on_1099k = s.platform in settings()["form_1099k"]
    gain = offset = None
    if cost is not None:
        gain = round(max(net - cost, 0.0), 2)
        offset = round(gross, 2) if on_1099k and gain == 0 else 0.0
    return {
        "gross": round(gross, 2),
        "net": round(net, 2),
        "gain": gain,
        "offset": offset,
        "on_1099k": on_1099k,
        "holding": holding,
        "complete": not missing,
        "missing": missing,
    }


def view(item: Item) -> dict:
    d = item.model_dump(mode="json")
    uid = item.uid
    try:
        item_dir(uid)
        archived = False
    except NotFound:
        archived = True
    try:
        ph = [str(p) for p in photos(uid)]
        photo_error = None
    except (Invalid, NotFound) as e:
        ph, photo_error = [], str(e)
    d["photos"] = ph
    d["photo_error"] = photo_error
    d["videos"] = [str(p) for p in videos(uid)]
    # What each platform's form gets, in order — the drafter uploads this list.
    d["upload"] = (
        {}
        if archived or photo_error
        else {
            plat: (
                [str(item_dir(uid) / "photos" / n) for n in lst.photos]
                if lst.photos is not None
                else ph
            )
            for plat, lst in item.platforms.items()
        }
    )
    d["archived"] = archived
    d["tax"] = tax_view(item)
    return d


