class Strict(BaseModel):
    """Base for every record model.

    `extra="ignore"` is deliberate (an unknown key must never make a
    model unloadable). The strictness that matters here is enforced instead by
    `_reject_unknown()` before validation: a misspelled field is a REFUSED write,
    not a silently dropped one.
    """

    model_config = ConfigDict(extra="ignore")


class PriceRange(Strict):
    low: float = Field(ge=0)
    high: float = Field(ge=0)

    @model_validator(mode="after")
    def _order(self) -> "PriceRange":
        if self.high < self.low:
            raise ValueError("price_market.high < low")
        return self


class Listing(Strict):
    """One platform: the seller's decisions for its draft (price, photos, category)
    and, once drafted, where the draft is. The drafter reads nothing else."""

    status: Literal["planned", "draft", "active", "delisted", "sold", "not_found"]
    date: Optional[Day] = None
    url: Optional[str] = None
    code: Optional[str] = None
    # Listed price on this platform, only when it differs from price_ask
    # (a repeat of price_ask is dropped by Item._invariants). Tax uses sale.price.
    price: Optional[float] = Field(default=None, ge=0)
    # Upload order, filenames in photos/. None = every photo in name order.
    photos: Optional[list[str]] = None
    # The platform's own category name, when it is not the obvious pick.
    category: Optional[str] = None

    @model_validator(mode="after")
    def _no_repeats(self) -> "Listing":
        dup = sorted({n for n in self.photos or [] if self.photos.count(n) > 1})
        if dup:
            raise ValueError(f"PHOTO_REPEAT: photos repeats {', '.join(dup)}")
        return self


class Acquisition(Strict):
    """The BUY side of the tax loop."""

    date: Optional[Day] = None
    date_basis: Literal[
        "order", "receipt", "memory", "release_date", "estimate", "unknown"
    ] = "unknown"
    price: Optional[float] = Field(default=None, ge=0)
    source: Optional[Literal["order_page", "receipt", "msrp", "seller", "estimate"]] = (
        None
    )
    confidence: Optional[Literal["high", "medium", "low"]] = None
    platform: Optional[AcqPlatform] = None
    order_id: Optional[str] = None
    note: Optional[str] = None
    question: Optional[str] = None

    @model_validator(mode="after")
    def _date_basis_agrees(self) -> "Acquisition":
        if self.date is None and self.date_basis != "unknown":
            raise ValueError("acquisition.date is null so date_basis must be 'unknown'")
        if self.date is not None and self.date_basis == "unknown":
            raise ValueError(
                "acquisition.date is set so date_basis must say where it came from"
            )
        return self


class Sale(Strict):
    """The SOLD side of the tax loop."""

    date: Optional[Day] = None
    date_basis: Literal["exact", "approx", "unknown"] = "unknown"
    platform: SalePlatform
    price: float = Field(ge=0)
    # What actually reached the seller's account for this sale (eBay payout after
    # its fees, label and collected tax; FB cash = price). Net is this number.
    received: Optional[float] = Field(default=None, ge=0)
    # Pre-2026-09-26 records carry these instead of `received`.
    fees: Optional[float] = Field(default=None, ge=0)
    shipping_charged: Optional[float] = Field(default=None, ge=0)
    shipping_cost: Optional[float] = Field(default=None, ge=0)
    refund: Optional[float] = Field(default=None, ge=0)
    order_id: Optional[str] = None
    lot: Optional[str] = None
    bundle_with: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def _checks(self) -> "Sale":
        if self.date is None and self.date_basis != "unknown":
            raise ValueError("sale.date is null so date_basis must be 'unknown'")
        if self.date is not None and self.date_basis == "unknown":
            raise ValueError(
                "sale.date is set so date_basis must be 'exact' or 'approx'"
            )
        for u in self.bundle_with:
            if not UID_RE.match(u):
                raise ValueError(f"sale.bundle_with: {u!r} is not a uid")
        return self


class Item(Strict):
    # identity
    uid: str = Field(pattern=r"^R\d{3,}$")
    name_en: Optional[str] = None
    name_zh: Optional[str] = None
    brand: Optional[str] = None
    model: Optional[str] = None
    model_confirmed: bool = False
    category: Category
    product_url: Optional[str] = None
    msrp: Optional[float] = Field(default=None, ge=0)
    key_specs: Optional[str] = None
    match_confidence: Optional[Literal["high", "medium", "low"]] = None
    open_question: Optional[str] = None
    notes: Optional[str] = None
    # condition
    condition: Optional[Condition] = None
    condition_zh: Optional[str] = None
    # pricing
    price_market: Optional[PriceRange] = None
    price_ask: Optional[float] = Field(default=None, ge=0)
    title_en: Optional[str] = None  # eBay caps at 80; enforced by _invariants
    title_zh: Optional[str] = None
    description_en: Optional[str] = None
    description_zh: Optional[str] = None
    # shipping
    weight_lb: Optional[float] = Field(default=None, gt=0)
    dims_in: Optional[str] = Field(
        default=None, pattern=r"^\d+(\.\d+)?x\d+(\.\d+)?x\d+(\.\d+)?$"
    )
    # listings
    platforms: dict[Platform, Listing] = Field(default_factory=dict)
    # buy side
    acquisition: Acquisition = Field(default_factory=Acquisition)
    # disposition
    disposition: Disposition = "available"
    disposition_date: Optional[Day] = None
    disposition_reason: Optional[str] = None
    # sell side
    sale: Optional[Sale] = None
    # meta
    created: Day
    updated: Day

    @model_validator(mode="after")
    def _invariants(self) -> "Item":
        errs: list[str] = []
        d = self.disposition

        if (d == "sold") != (self.sale is not None):
            errs.append("SALE_BLOCK_MISMATCH: disposition 'sold' <=> a sale block")
        if d == "available" and self.price_ask is None:
            errs.append("ASK_PRICE_REQUIRED: an available item needs price_ask")
        if d == "available" and self.condition is None:
            errs.append("CONDITION_REQUIRED: an available item needs condition")
        if d == "available" and self.title_en and len(self.title_en) > 80:
            errs.append(
                f"TITLE_TOO_LONG: title_en is {len(self.title_en)} chars — eBay caps at 80"
            )
        for plat, lst in self.platforms.items():
            if lst.price is not None and lst.price == self.price_ask:
                lst.price = None
            cap = PHOTO_LIMIT.get(plat)
            if cap and lst.photos and len(lst.photos) > cap:
                errs.append(
                    f"PHOTO_LIMIT: platforms.{plat}.photos has {len(lst.photos)} — "
                    f"{plat} takes {cap}"
                )
            if d == "available" and lst.status == "planned":
                need = ["title_en", "description_en"]
                if plat == "ebay":
                    need += ["weight_lb", "dims_in"]  # calculated shipping
                missing = [f for f in need if getattr(self, f) is None]
                if missing:
                    errs.append(
                        f"BRIEF_INCOMPLETE: planned {plat} needs {', '.join(missing)} "
                        "— the drafter fills the form from the record only"
                    )
        if d == "sold" and self.acquisition.price is None:
            errs.append(
                "ACQUISITION_REQUIRED: a sold item needs acquisition.price (cost basis)"
            )
        if d in {"kept", "disposed", "void"}:
            if self.disposition_date is None:
                errs.append(f"DISPOSITION_INCOMPLETE: '{d}' needs disposition_date")
            if d != "kept" and not self.disposition_reason:
                errs.append(f"DISPOSITION_INCOMPLETE: '{d}' needs disposition_reason")
        if (
            self.sale
            and self.sale.date
            and self.acquisition.date
            and self.acquisition.date > self.sale.date
        ):
            errs.append("DATE_ORDER: acquisition.date is after sale.date")
        if self.sale:
            gross = self.sale.price + (self.sale.shipping_charged or 0)
            if (self.sale.refund or 0) > gross:
                errs.append(
                    "REFUND_EXCEEDS_GROSS: sale.refund > price + shipping_charged"
                )
        if errs:
            raise ValueError("\n".join(errs))
        return self


