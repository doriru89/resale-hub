def _cmd_sold(a) -> None:
    before, _ = load(a.uid)
    if before.disposition == "sold":
        raise Invalid(f"ALREADY_SOLD: {a.uid} is sold — fix a field with `set`")
    price = a.price
    if price is None and a.platform in CASH:
        # FB: it sells at what it was listed for on that platform
        lst = before.platforms.get(a.platform)
        price = lst.price if lst and lst.price is not None else before.price_ask
    if price is None:
        raise Invalid(f"PRICE_REQUIRED: --price is required for {a.platform}")
    received = a.received
    if received is None and a.platform in CASH:
        received = price
    sale = {
        "date": a.date,
        "date_basis": "approx" if a.approx else "exact",
        "platform": a.platform,
        "price": price,
        "received": received,
        "shipping_charged": a.ship_charged,
        "order_id": a.order,
        "lot": a.lot,
    }
    patch: dict[str, Any] = {
        "disposition": "sold",
        "sale": {k: v for k, v in sale.items() if v is not None},
    }
    item, rev = update(a.uid, patch, expected_rev=a.rev)
    print(
        json.dumps(
            {
                "ok": True,
                "uid": item.uid,
                "rev": rev,
                "archived": str(archive_path(item).relative_to(base())),
                "tax": tax_view(item),
            },
            ensure_ascii=False,
        )
    )


