@contextmanager
def _flock() -> Iterator[None]:
    """One store-wide lock. Per-folder locks would vanish mid-hold when the
    folder is archived; a single user never contends enough to care."""
    path = items_dir() / ".lock"
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "a+") as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        try:
            yield
        finally:
            fcntl.flock(fh, fcntl.LOCK_UN)


def next_uid() -> str:
    """Highest uid in items/ OR years/ + 1. A uid is NEVER reused — scanning
    only items/ would hand out R001 again once R001 moved to years/."""
    n = 0
    d = items_dir()
    if d.exists():
        for sub in d.iterdir():
            if sub.is_dir() and DIR_RE.match(sub.name):
                n = max(n, int(sub.name.split("-", 1)[0][1:]))
    y = years_dir()
    if y.exists():
        for f in y.glob("*/R*.yaml"):
            m = ARCHIVE_RE.match(f.name)
            if m and YEAR_RE.match(f.parent.name):
                n = max(n, int(m.group(1)[1:]))
    return f"R{n + 1:03d}"


def _deep_merge(dst: dict, patch: dict) -> dict:
    """Dotted keys allowed: {'acquisition.price': 30} nests correctly."""
    out = dict(dst)
    for key, val in patch.items():
        if "." in key:
            head, rest = key.split(".", 1)
            sub = out.get(head)
            out[head] = _deep_merge(sub if isinstance(sub, dict) else {}, {rest: val})
        elif isinstance(val, dict) and isinstance(out.get(key), dict):
            out[key] = _deep_merge(out[key], val)
        else:
            out[key] = val
    return out


def _reject_unknown(
    payload: dict, model: type[BaseModel] = None, path: str = ""
) -> None:
    """Refuse a write that names a field the schema does not have.

    pydantic is configured `extra="ignore"`, so without this a
    `cost_basis=30` patch would return 200 and change nothing. Recurses into the
    nested record models; `platforms` is a dict keyed by platform, so its values
    are checked against Listing rather than its keys against a field list.
    """
    model = model or Item
    fields = model.model_fields
    for key, val in payload.items():
        here = f"{path}{key}"
        if key not in fields:
            near = ", ".join(sorted(fields)[:6])
            raise Invalid(
                f"UNKNOWN_FIELD: {here!r} is not in the schema (fields include: {near}, …)"
            )
        if not isinstance(val, dict):
            continue
        ann = fields[key].annotation
        if here.endswith("platforms"):
            for plat, listing in val.items():
                if isinstance(listing, dict):
                    _reject_unknown(listing, Listing, f"{here}.{plat}.")
            continue
        for cand in (ann, *getattr(ann, "__args__", ())):
            if isinstance(cand, type) and issubclass(cand, BaseModel):
                _reject_unknown(val, cand, f"{here}.")
                break


def _check_status_writes(patch: dict, before: Item | None) -> None:
    """We only ever hold drafts; the seller publishes. A historical value
    already on the record may be re-sent unchanged (the dashboard does that)."""
    for plat, listing in (patch.get("platforms") or {}).items():
        if not isinstance(listing, dict) or "status" not in listing:
            continue
        s = listing["status"]
        prev = before.platforms.get(plat) if before else None
        if s not in STATUS_WRITABLE and not (prev and prev.status == s):
            raise Invalid(
                f"STATUS_WRITE: platforms.{plat}.status={s!r} — writable values are "
                + ", ".join(sorted(STATUS_WRITABLE))
            )


def _validate(payload: dict) -> Item:
    try:
        return Item.model_validate(payload)
    except ValidationError as e:
        raise Invalid(*(_fmt(err) for err in e.errors())) from e


def _close_checks(item: Item) -> None:
    if item.disposition == "sold":
        t = tax_view(item)
        if t and not t["complete"]:
            raise Invalid(
                f"TAX_INCOMPLETE: {item.uid} missing {', '.join(t['missing'])} — a sale "
                "leaves items/ when it is recorded, so there is no later backfill. Read "
                "the values off the platform order, or ask the seller; never guess."
            )


def archive_path(item: Item) -> Path:
    d = (
        item.sale.date
        if item.disposition == "sold" and item.sale
        else item.disposition_date
    )
    if d is None:
        raise Invalid(f"ARCHIVE_NO_DATE: {item.uid} has no date to file it under")
    return years_dir() / str(d.year) / f"{item.uid}.yaml"


def _write_record(current: Path, item: Item) -> Path:
    """Write `item`. A closed record never stays in items/: it is written to
    years/<year>/, read back, and only then is the item folder (photos and
    all) removed. Caller holds _flock()."""
    if item.disposition not in CLOSED:
        _atomic_write(current, item)
        return current
    _close_checks(item)
    dest = archive_path(item)
    if dest == current:
        _atomic_write(current, item)
        return current
    if dest.exists():
        raise Conflict(f"{item.uid}: {dest.relative_to(base())} already exists")
    dest.parent.mkdir(parents=True, exist_ok=True)
    _atomic_write(dest, item)
    if _parse(dest).model_dump() != item.model_dump():
        dest.unlink()
        raise ResaleError(f"{item.uid}: archive read-back differs — nothing removed")
    if _is_archived(current):
        current.unlink()
    else:
        shutil.rmtree(current.parent)
    return dest


