def _dir_bytes(d: Path) -> int:
    return sum(p.stat().st_size for p in d.rglob("*") if p.is_file())


def _cmd_archive(a) -> None:
    """Move every closed record still in items/ to years/. Validates all first:
    one incomplete sale refuses the whole sweep, nothing moves."""
    with _flock():
        closed = [
            (i, p) for i, _, p in _scan(archived=False) if i.disposition in CLOSED
        ]
        errs: list[str] = []
        for item, _ in closed:
            try:
                _close_checks(item)
                if archive_path(item).exists():
                    errs.append(
                        f"{item.uid}: {archive_path(item).relative_to(base())} already exists"
                    )
            except Invalid as e:
                errs.extend(e.errors)
        if errs:
            _die(1, *errs)
        freed = 0
        by_year: dict[str, int] = {}
        for item, path in closed:
            freed += _dir_bytes(path.parent)
            dest = _write_record(path, item)
            by_year[dest.parent.name] = by_year.get(dest.parent.name, 0) + 1
    print(
        json.dumps(
            {
                "ok": True,
                "archived": len(closed),
                "by_year": by_year,
                "freed_mb": round(freed / 1e6, 1),
            },
            ensure_ascii=False,
        )
    )


def _cmd_check(a) -> None:
    try:
        rows = _scan()
    except Invalid as e:
        _die(1, *e.errors)
        return
    problems: list[str] = []
    for item, _, path in rows:
        if not _is_archived(path):
            if item.disposition in CLOSED:
                problems.append(
                    f"{item.uid}: {item.disposition} but still in items/ — "
                    "run `resale_store.py archive`"
                )
            else:
                try:
                    problems.extend(_listing_photo_errors(item, photos(item.uid)))
                except Invalid as e:
                    problems.extend(e.errors)
        if item.disposition == "available":
            if item.condition is None:
                problems.append(f"{item.uid}: available with no condition")
            if item.description_en and re.search(
                r"local (pickup|sale)|free delivery|pickup at",
                item.description_en,
                re.I,
            ):
                problems.append(
                    f"{item.uid}: description_en contains delivery-policy text. "
                    "description_en is the platform-neutral body; the delivery sentence "
                    "is appended on the FB form only (references/list.md). "
                    f"Strip it: resale_store.py set {item.uid} description_en=<body>"
                )
        if item.disposition == "sold" and (t := tax_view(item)) and not t["complete"]:
            problems.append(f"{item.uid}: sale missing {', '.join(t['missing'])}")
    if problems:
        _die(1, *problems)
    print(json.dumps({"ok": True, "items": len(rows)}, ensure_ascii=False))


